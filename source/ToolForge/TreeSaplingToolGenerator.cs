        internal static string GenerateRenderable(ToolForgeProject project,
            string profile)
        {
            string suffix = String.Equals(profile, "fp",
                StringComparison.OrdinalIgnoreCase) ? "Fp" : "Tp";
            string textureStem = ResolveTextureStem(project);
            return "{\n" +
                "  \"lodList\" : [\n" +
                "    {\n" +
                "      \"maxViewDistance\" : 1000.0,\n" +
                "      \"mesh\" : \"$SURVIVAL_DATA/Character/Char_Tools/ScrapLab/TreeSaplings/TreeSaplingHeld" + suffix + ".dae\",\n" +
                "      \"subMeshMap\" : {\n" +
                "        \"" + JsonEscape(project.SourceMesh.MaterialName) + "\" : {\n" +
                "          \"material\" : \"DifAsgNorAlpha\",\n" +
                "          \"textureList\" : [\n" +
                "            \"$GAME_DATA/Objects/Textures/plants/" + textureStem + "_dif.tga\",\n" +
                "            \"$GAME_DATA/Objects/Textures/plants/" + textureStem + "_asg.tga\",\n" +
                "            \"$GAME_DATA/Objects/Textures/plants/" + textureStem + "_nor.tga\"\n" +
                "          ]\n" +
                "        }\n" +
                "      }\n" +
                "    }\n" +
                "  ]\n" +
                "}\n";
        }

        internal static string ResolveTextureStem(ToolForgeProject project)
        {
            string mode = project == null || project.SourceMesh == null
                ? String.Empty : project.SourceMesh.TextureMode;
            if (String.Equals(mode, "vanilla-poleplant",
                StringComparison.OrdinalIgnoreCase))
                return "obj_plants_poleplant";
            if (String.Equals(mode, "vanilla-leafplant",
                StringComparison.OrdinalIgnoreCase))
                return "obj_plants_leafplant";
            throw new InvalidDataException("Unsupported held-tool texture mode '" +
                mode + "'. Re-import the source FBX so Tool Forge can match its material atlas.");
        }

        internal static string GenerateVisualLua(ToolForgeProject project)
        {
            StringBuilder text = new StringBuilder();
            text.Append("-- Generated by ScrapLab Tool Forge. Do not edit this generated copy.\n");
            text.Append("-- ScrapLab invalidates the compiled Mesh cache whenever this held asset changes.\n");
            text.Append("ScrapLabTreeSaplingVisual = ScrapLabTreeSaplingVisual or {}\n\n");
            text.Append("local HeldRenderableTp = \"")
                .Append(HeldRenderableTpGamePath).Append("\"\n");
            text.Append("local HeldRenderableFp = \"")
                .Append(HeldRenderableFpGamePath).Append("\"\n");
            text.Append("local RenderablesTp = {\n")
                .Append("\t\"$SURVIVAL_DATA/Character/Char_Male/Animations/char_male_tp_bucket.rend\",\n")
                .Append("\t\"$SURVIVAL_DATA/Character/Char_bucket/char_bucket_tp_animlist.rend\",\n")
                .Append("\tHeldRenderableTp\n}\n");
            text.Append("local RenderablesFp = {\n")
                .Append("\t\"$SURVIVAL_DATA/Character/Char_Male/Animations/char_male_fp_bucket.rend\",\n")
                .Append("\t\"$SURVIVAL_DATA/Character/Char_bucket/char_bucket_fp_animlist.rend\",\n")
