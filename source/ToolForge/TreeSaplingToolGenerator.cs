                .Append("\t\ttool:setFpColor( color )\n")
                .Append("\tend\n")
                .Append("end\n");
            return text.ToString();
        }

        internal static string GenerateIntegratedTool(string source,
            ToolForgeProject project)
        {
            const string generatedDofile =
                "dofile \"$SURVIVAL_DATA/Scripts/ScrapLab/Parts/TreeSaplings/TreeSaplingVisual.generated.lua\"";
            if (Count(source, generatedDofile) == 0)
            {
                const string anchor =
                    "dofile \"$SURVIVAL_DATA/Scripts/game/survival_items.lua\"";
                RequireCount(source, anchor, 1);
                source = source.Replace(anchor, anchor + "\n" + generatedDofile);
            }
            else RequireCount(source, generatedDofile, 1);

            string loadAnimations =
                "function TreeSaplingToolBase.cl_loadAnimations( self )\n" +
                "\tself.tpAnimations = createTpAnimations( self.tool, {\n" +
                "\t\tidle = { \"bucket_idle\", { looping = true } },\n" +
                "\t\tuse = { \"bucket_use_full\", { nextAnimation = \"idle\" } },\n" +
                "\t\tpickup = { \"bucket_pickup\", { nextAnimation = \"idle\" } },\n" +
                "\t\tputdown = { \"bucket_putdown\" }\n" +
                "\t} )\n" +
                "\tlocal movement = {\n" +
                "\t\tidle = \"bucket_idle\", runFwd = \"bucket_run\",\n" +
                "\t\trunBwd = \"bucket_runbwd\", sprint = \"bucket_sprint_idle\",\n" +
                "\t\tsprintLeft = \"bucket_sprint_left\", sprintRight = \"bucket_sprint_right\",\n" +
                "\t\tjump = \"bucket_jump\", jumpUp = \"bucket_jump_up\",\n" +
                "\t\tjumpDown = \"bucket_jump_down\", land = \"bucket_jump_land\",\n" +
                "\t\tlandFwd = \"bucket_jump_land_fwd\", landBwd = \"bucket_jump_land_bwd\",\n" +
                "\t\tlandLeft = \"bucket_jump_land_left\", landRight = \"bucket_jump_land_right\",\n" +
                "\t\tcrouchIdle = \"bucket_crouch_idle\", crouchFwd = \"bucket_crouch_run\",\n" +
                "\t\tcrouchBwd = \"bucket_crouch_runbwd\"\n" +
                "\t}\n" +
                "\tfor name, animation in pairs( movement ) do\n" +
                "\t\tself.tool:setMovementAnimation( name, animation )\n" +
                "\tend\n" +
                "\tif self.tool:isLocal() then\n" +
                "\t\tself.fpAnimations = createFpAnimations( self.tool, {\n" +
                "\t\t\tidle = { \"bucket_idle\", { looping = true } },\n" +
                "\t\t\tuse = { \"bucket_use_full\", { nextAnimation = \"idle\" } },\n" +
                "\t\t\tsprintInto = { \"bucket_sprint_into\", { nextAnimation = \"sprintIdle\", blendNext = 0.2 } },\n" +
                "\t\t\tsprintIdle = { \"bucket_sprint_idle\", { looping = true } },\n" +
                "\t\t\tsprintExit = { \"bucket_sprint_exit\", { nextAnimation = \"idle\", blendNext = 0 } },\n" +
                "\t\t\tjump = { \"bucket_jump\", { nextAnimation = \"idle\" } },\n" +
                "\t\t\tland = { \"bucket_jump_land\", { nextAnimation = \"idle\" } },\n" +
                "\t\t\tequip = { \"bucket_pickup\", { nextAnimation = \"idle\" } },\n" +
                "\t\t\tunequip = { \"bucket_putdown\" }\n" +
                "\t\t} )\n" +
                "\tend\n" +
                "\tsetTpAnimation( self.tpAnimations, \"idle\", 5.0 )\n" +
                "\tself.blendTime = 0.2\n" +
                "end\n";
            source = ReplaceFunctionBefore(source,
                "TreeSaplingToolBase.cl_loadAnimations",
                "TreeSaplingToolBase.cl_updateRenderables", loadAnimations);

            string updateRenderables =
                "function TreeSaplingToolBase.cl_updateRenderables( self )\n" +
                "\tScrapLabTreeSaplingVisual.apply( self.tool, self.config.color )\n" +
                "end\n";
            source = ReplaceFunctionBefore(source,
                "TreeSaplingToolBase.cl_updateRenderables",
                "TreeSaplingToolBase.client_onDestroy", updateRenderables);
            foreach (ToolVariant variant in project.Variants)
            {
                RequireCount(source, variant.ItemUuid, 1);
            }
            return source;
        }

