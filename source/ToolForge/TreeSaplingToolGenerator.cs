                text.Append("\t").Append(variant.Key).Append(" = sm.color.new( 0x")
                    .Append(variant.Color.ToLowerInvariant()).Append("ff ),\n");
            text.Append("}\n\n");
            text.Append("sm.tool.preloadRenderables( { HeldRenderableTp, HeldRenderableFp } )\n")
                .Append("sm.tool.preloadRenderables( RenderablesTp )\n")
                .Append("sm.tool.preloadRenderables( RenderablesFp )\n\n");
            text.Append("function ScrapLabTreeSaplingVisual.apply( tool, color )\n")
                .Append("\ttool:setTpRenderables( RenderablesTp )\n")
                .Append("\ttool:setTpColor( color )\n")
