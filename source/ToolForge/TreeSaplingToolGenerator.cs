        private static string ReplaceFunctionBefore(string source,
            string functionName, string nextFunctionName, string replacement)
        {
            string startMarker = "function " + functionName;
            string nextMarker = "function " + nextFunctionName;
            RequireCount(source, startMarker, 1);
            RequireCount(source, nextMarker, 1);
            int start = source.IndexOf(startMarker, StringComparison.Ordinal);
            int next = source.IndexOf(nextMarker, start + startMarker.Length,
                StringComparison.Ordinal);
            if (next <= start)
                throw new InvalidDataException("The protected Lua function order changed.");
            return source.Substring(0, start) + replacement + "\n" +
                source.Substring(next);
        }

        private static void RequireCount(string text, string value, int expected)
        {
            int count = Count(text, value);
            if (count != expected)
                throw new InvalidDataException("Protected text '" + value +
                    "' must appear " + expected + " time(s); found " + count + ".");
        }

        private static int Count(string text, string value)
        {
            int count = 0, index = 0;
            while ((index = text.IndexOf(value, index,
                StringComparison.Ordinal)) >= 0)
            {
                count++;
                index += value.Length;
            }
            return count;
        }

        private static string JsonEscape(string value)
        {
            return (value ?? String.Empty).Replace("\\", "\\\\")
                .Replace("\"", "\\\"");
        }
